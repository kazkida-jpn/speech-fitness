/** How many sentences one practice session reads. */
export const SENTENCES_PER_SESSION = 10;

/** YYYY-MM-DD in local time, so the daily set flips at the user's midnight. */
export function localDayKey(date: Date) {
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${date.getFullYear()}-${month}-${day}`;
}

/** FNV-1a: a small, stable string hash for seeding. */
function hashString(text: string) {
  let hash = 2166136261;
  for (const char of text) {
    hash ^= char.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 16777619) >>> 0;
  }
  return hash;
}

/** mulberry32: a tiny deterministic PRNG, good enough for shuffling. */
function seededRandom(seed: number) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * The sentences for today's session: a deterministic subset of the drill's pool, so
 * reopening the drill on the same day shows the same set and tomorrow shows another.
 */
export function sessionSentences(drill: Drill, date = new Date()): string[] {
  const random = seededRandom(hashString(`${drill.id}:${localDayKey(date)}`));
  const pool = [...drill.sentences];
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(SENTENCES_PER_SESSION, pool.length));
}

/** Picks up to three drill ids whose focus is mentioned in a diagnosis text. */
export function recommendDrills(text: string): DrillId[] {
  const rules: [RegExp, DrillId][] = [
    [/サ行|ザ行|シ|ジ|チ|ツ|ずつ/, 'sibilants'],
    [/カ行|ガ行|タ行|ダ行|パ行|バ行|ラ行|子音/, 'consonants'],
    [/長音|促音|撥音|切符|音の長さ/, 'mora'],
    [/語尾|文末|です|ます/, 'endings'],
    [/つながり|連続|なめらか/, 'connections'],
    [/リズム|一定|ばらつき/, 'rhythm'],
    [/間|呼吸|停止/, 'pauses'],
    [/早口|速度|速く/, 'speed'],
  ];
  const matches = rules.filter(([pattern]) => pattern.test(text)).map(([, id]) => id);
  return Array.from(new Set(matches)).slice(0, 3);
}
